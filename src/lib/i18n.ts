const DICT: Record<AppLanguage, Record<string, string>> = { en: EN, fr: FR, es: ES, de: DE };

export function languageFromPref(value?: string): AppLanguage {
  const v = (value || '').toLowerCase();
  if (v.startsWith('fr')) return 'fr';
  if (v.startsWith('es') || v.includes('spanish')) return 'es';
  if (v.startsWith('de') || v.includes('german')) return 'de';
  return 'en';
}

export function t(lang: AppLanguage, key: string) {
  return DICT[lang]?.[key] || DICT.en[key] || key;
}
